import math
import sys
from datetime import datetime, timezone, timedelta

IST = timezone(timedelta(hours=5, minutes=30))

# ?????????????????????????????????????????????????????????????????????????????
# Minimal test harness
# ?????????????????????????????????????????????????????????????????????????????

passed = 0
failed = 0

def test(name, fn):
    global passed, failed
    try:
        fn()
        print(f"  [PASS]  {name}")
        passed += 1
    except AssertionError as e:
        print(f"  [FAIL]  {name}")
        print(f"       {e}")
        failed += 1

def close(a, b, tol=1e-6, msg=None):
    assert abs(a - b) <= tol, msg or f"Expected {a} ? {b} (tol {tol})"

# ?????????????????????????????????????????????????????????????????????????????
# Solar model (same constants as Code.gs / index.html)
# ?????????????????????????????????????????????????????????????????????????????

EFFICIENCY      = 0.92
TEMP_COEFF      = 0.004
TEMP_AMBIENT_K  = 0.03
REF_TEMP        = 25.0
MIN_PERF_RATIO  = 0.5

def expected_kw(capacity_kwp, radiation_wm2, ambient_c):
    if radiation_wm2 <= 0:
        return 0.0
    cell_temp   = ambient_c + TEMP_AMBIENT_K * radiation_wm2
    temp_factor = max(MIN_PERF_RATIO, 1.0 - TEMP_COEFF * (cell_temp - REF_TEMP))
    return capacity_kwp * (radiation_wm2 / 1000.0) * EFFICIENCY * temp_factor

# ?????????????????????????????????????????????????????????????????????????????
# Trapezoid energy integration
# ?????????????????????????????????????????????????????????????????????????????

def trapezoid_energy(readings, gap_max_sec=3 * 3600):
    """readings: list of {'t': datetime or float(epoch_s), 'power_kw': float}"""
    if not readings or len(readings) < 2:
        return 0.0
    def to_epoch(t):
        if isinstance(t, datetime):
            return t.timestamp()
        return float(t)
    sorted_r = sorted(readings, key=lambda r: to_epoch(r['t']))
    energy = 0.0
    for i in range(1, len(sorted_r)):
        dt_sec = to_epoch(sorted_r[i]['t']) - to_epoch(sorted_r[i-1]['t'])
        if dt_sec <= 0 or dt_sec > gap_max_sec:
            continue
        avg_kw = (sorted_r[i]['power_kw'] + sorted_r[i-1]['power_kw']) / 2.0
        energy += avg_kw * (dt_sec / 3600.0)
    return energy

# ?????????????????????????????????????????????????????????????????????????????
# Radiation interpolation (hourly points shifted -30 min)
# ?????????????????????????????????????????????????????????????????????????????

def interpolate_radiation(hourly_points, target_epoch):
    """hourly_points: [{'t': epoch_s, 'rad': W/m²}]"""
    if not hourly_points:
        return None
    if target_epoch <= hourly_points[0]['t']:
        return hourly_points[0]['rad']
    if target_epoch >= hourly_points[-1]['t']:
        return hourly_points[-1]['rad']
    for i in range(1, len(hourly_points)):
        if target_epoch <= hourly_points[i]['t']:
            span = hourly_points[i]['t'] - hourly_points[i-1]['t']
            frac = (target_epoch - hourly_points[i-1]['t']) / span
            return hourly_points[i-1]['rad'] + frac * (hourly_points[i]['rad'] - hourly_points[i-1]['rad'])
    return None

def make_hourly(rad_values, base_epoch):
    return [{'t': base_epoch + i * 3600, 'rad': v} for i, v in enumerate(rad_values)]

# ?????????????????????????????????????????????????????????????????????????????
# Timestamp parsing
# ?????????????????????????????????????????????????????????????????????????????

def parse_timestamp(raw):
    if raw is None:
        return None
    if isinstance(raw, (int, float)):
        if raw < 1e12:
            return datetime.fromtimestamp(raw, tz=timezone.utc)
        return datetime.fromtimestamp(raw / 1000.0, tz=timezone.utc)
    s = str(raw).strip()
    # ISO with zone
    try:
        return datetime.fromisoformat(s)
    except ValueError:
        pass
    # yyyy-mm-dd hh:mm
    for fmt in ('%Y-%m-%d %H:%M', '%d/%m/%Y %H:%M'):
        try:
            dt = datetime.strptime(s, fmt)
            return dt.replace(tzinfo=IST)
        except ValueError:
            pass
    return None

# ?????????????????????????????????????????????????????????????????????????????
# Performance ratio
# ?????????????????????????????????????????????????????????????????????????????

def performance_ratio(energy_kwh, capacity_kwp, sun_hours):
    if sun_hours < 0.05:
        return None
    return min(energy_kwh / (sun_hours * capacity_kwp), 1.2)

# ?????????????????????????????????????????????????????????????????????????????
# Ingest validation
# ?????????????????????????????????????????????????????????????????????????????

def validate_reading(r, capacity_kwp, ingest_key):
    errors = []
    if r.get('key') != ingest_key:
        errors.append('bad key')
    pw = None
    if 'power_kw' in r and r['power_kw'] is not None:
        pw = float(r['power_kw'])
    elif 'power_w' in r and r['power_w'] is not None:
        pw = float(r['power_w']) / 1000.0
    if pw is None or math.isnan(pw):
        errors.append('missing power')
    elif pw < 0:
        errors.append('negative power')
    elif pw > 3 * capacity_kwp:
        errors.append('Is the logger sending watts? Use power_w')
    return errors

