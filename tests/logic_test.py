# Named functions for ingest validation tests
def test_valid(): assert not validate_reading({'key':'abc','power_kw':4.2}, 10, 'abc')
def test_bad_key(): assert 'bad key' in validate_reading({'key':'x','power_kw':4.2}, 10, 'abc')
def test_no_power(): assert 'missing power' in validate_reading({'key':'abc'}, 10, 'abc')
def test_neg_power(): assert 'negative power' in validate_reading({'key':'abc','power_kw':-1}, 10, 'abc')
def test_power_w(): assert not validate_reading({'key':'abc','power_w':4200}, 10, 'abc')
def test_too_high(): assert any('watts' in e for e in validate_reading({'key':'abc','power_kw':31}, 10, 'abc'))

test("validate: valid reading passes",           test_valid)
test("validate: wrong key rejected",             test_bad_key)
test("validate: missing power rejected",         test_no_power)
test("validate: negative power rejected",        test_neg_power)
test("validate: power_w auto-converted",         test_power_w)
test("validate: power > 3× capacity hint",       test_too_high)

