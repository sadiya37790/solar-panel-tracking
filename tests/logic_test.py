# Base epoch for test data (2025-11-01 06:00 UTC)
BASE = datetime(2025, 11, 1, 6, 0, 0, tzinfo=timezone.utc).timestamp()

print("\n?  Solar model tests")

test("expectedKw: zero at night (radiation=0)",
     lambda: close(expected_kw(10, 0, 30), 0.0))

test("expectedKw: STC (1000 W/m², 25°C)", lambda: (
    close(expected_kw(10, 1000, 25), 10 * 1.0 * 0.92 * 0.88, tol=0.001)
))

test("expectedKw: temperature floor (very high temp)", lambda: (
    close(expected_kw(10, 10000, 60), 10 * 10.0 * 0.92 * 0.5, tol=0.001)
))

test("expectedKw: scales linearly with capacity", lambda: (
    close(expected_kw(10, 500, 30), 2 * expected_kw(5, 500, 30), tol=0.001)
))

print("\n?  Trapezoid energy integration tests")

test("trapezoidEnergy: empty ? 0", lambda: close(trapezoid_energy([]), 0.0))

test("trapezoidEnergy: single point ? 0",
     lambda: close(trapezoid_energy([{'t': BASE, 'power_kw': 5}]), 0.0))

test("trapezoidEnergy: constant 1 kW over 1 h = 1 kWh", lambda: (
    close(trapezoid_energy([
        {'t': BASE,        'power_kw': 1},
        {'t': BASE + 3600, 'power_kw': 1},
    ]), 1.0)
))

test("trapezoidEnergy: ramp 0?2 kW over 1 h = 1 kWh (triangle)", lambda: (
    close(trapezoid_energy([
        {'t': BASE,        'power_kw': 0},
        {'t': BASE + 3600, 'power_kw': 2},
    ]), 1.0)
))

test("trapezoidEnergy: 4-hour gap skipped", lambda: (
    close(trapezoid_energy([
        {'t': BASE,            'power_kw': 5},
        {'t': BASE + 4*3600,   'power_kw': 5},
    ], gap_max_sec=3*3600), 0.0)
))

test("trapezoidEnergy: out-of-order input sorted", lambda: (
    close(trapezoid_energy([
        {'t': BASE + 3600, 'power_kw': 4},  # later first
        {'t': BASE,        'power_kw': 2},
    ]), 3.0)
))

print("\n?  Radiation interpolation tests")

test("interpolate: exact match", lambda: (
    close(interpolate_radiation(make_hourly([0,100,500,800,500,100,0], BASE),
                                BASE + 2*3600), 500.0)
))

test("interpolate: midpoint between two", lambda: (
    close(interpolate_radiation(make_hourly([0, 1000], BASE),
                                BASE + 1800), 500.0)
))

test("interpolate: clamp before first", lambda: (
    close(interpolate_radiation(make_hourly([200, 400], BASE),
                                BASE - 3600), 200.0)
))

test("interpolate: clamp after last", lambda: (
    close(interpolate_radiation(make_hourly([200, 400], BASE),
                                BASE + 7200), 400.0)
))

print("\n?  Timestamp parsing tests")

def test_ts_iso():
    d = parse_timestamp('2025-11-01T08:30:00+05:30')
    assert d is not None and d.utcoffset() is not None
    utc = d.astimezone(timezone.utc)
    assert utc.hour == 3 and utc.minute == 0, f"Expected 03:00 UTC, got {utc.hour}:{utc.minute}"
test("parseTimestamp: ISO with +05:30", test_ts_iso)

def test_ts_ymdhm():
    d = parse_timestamp('2025-11-01 08:30')
    assert d is not None
    utc = d.astimezone(timezone.utc)
    assert utc.hour == 3
test("parseTimestamp: yyyy-mm-dd hh:mm ? IST", test_ts_ymdhm)

def test_ts_dmy():
    d = parse_timestamp('01/11/2025 08:30')
    assert d is not None
    utc = d.astimezone(timezone.utc)
    assert utc.hour == 3
test("parseTimestamp: dd/mm/yyyy hh:mm ? IST", test_ts_dmy)

def test_ts_epoch_s():
    epoch = 1_700_000_000
    d = parse_timestamp(epoch)
    assert d is not None
    assert abs(d.timestamp() - epoch) < 1
test("parseTimestamp: epoch seconds", test_ts_epoch_s)

def test_ts_epoch_ms():
    ms = 1_700_000_000_000
    d = parse_timestamp(ms)
    assert d is not None
    assert abs(d.timestamp() * 1000 - ms) < 1000
test("parseTimestamp: epoch milliseconds", test_ts_epoch_ms)

def test_ts_none():
    assert parse_timestamp(None) is None
test("parseTimestamp: None ? None", test_ts_none)


print("\n?  Performance ratio tests")

def assert_pr_none(v):
    assert v is None, f"Expected None, got {v}"

test("PR: sun-hours < 0.05 ? None",
     lambda: assert_pr_none(performance_ratio(0.5, 10, 0.04)))

test("PR: perfect 0.92 output",
     lambda: close(performance_ratio(9.2, 10, 1.0), 0.92))

test("PR: cap at 120%",
     lambda: close(performance_ratio(200, 10, 1.0), 1.2))

test("PR: fair 65%",
     lambda: close(performance_ratio(6.5, 10, 1.0), 0.65))

